})

onMounted(() => {
  nextTick(() => {
    const el = marker.value
    if (!el) return

    // Find the closest <article> ancestor
    const article = el.closest('article')
    if (!article) return

    // Collect all direct children of the article
    const children = Array.from(article.children)
    if (children.length < 3) return

    // Pick a random position in the middle third of the article
    const start = Math.floor(children.length * 0.3)
    const end = Math.floor(children.length * 0.7)
    const randomIndex = start + Math.floor(Math.random() * (end - start))

    // Move the marker element to the random position
    const target = children[randomIndex]
    if (target && target !== el) {
      article.insertBefore(el, target)
    }
  })
})
