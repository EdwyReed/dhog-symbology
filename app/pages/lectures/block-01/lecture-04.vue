      </p>

      <h3 class="lecture-h3">
        I. Что перед тобой?
      </h3>

      <h4 class="lecture-h4">
        1. Назовите объект.
      </h4>
      <p class="lecture-text">
        Сайлас нарисовал на доске круг.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Это круг.
      </p>
      <br/>
      <p class="lecture-text">
        Он обвёл его ещё раз, медленно.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Не защита, не вечность, не гармония вселенной. Круг. Просто форма, геометрия. Символом он станет, когда вы определите контекст, систему, грани и функцию. Первый шаг нужен, чтобы вы не начали сочинять раньше, чем увидели.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — В Символогии первое правило чтения простое: пока вы не назвали вещь нормально — вы уже сочиняете.
      </p>

      <h4 class="lecture-h4">
        2. Найдите контекст. Где он стоит и зачем.
      </h4>
      <p class="lecture-text">
        Профессор рядом поставил короткие пометки:
      </p>
      <br/>
      <p class="lecture-text italic">
        где / кто / когда / для кого / зачем
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Один и тот же круг в разных местах — это разные вещи.
      </p>
      <br/>
      <p class="lecture-text">
        <span class="font-extrabold">— Круг в учебной тетради — упражнение. Круг на полу ритуального зала — схема. Круг на шее человека — знак. Круг, выжженный на внутренней стороне двери, которую никто не открывает…</span> — он сделал паузу и посмотрел поверх очков. — <span class="font-extrabold">Это уже повод не трогать руками и не строить догадки вслух.</span>
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Хотя вы всё равно будете. Я вас знаю.
      </p>

