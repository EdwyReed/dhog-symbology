      </p>
      <br/>
      <p class="lecture-text-bold">
        — Симвология не запрещает вам чувствовать. Она запрещает вам останавливаться на этом.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Я дам вам метод. Запомните его, и вы перестанете тонуть в трактовках. А если не запомните — будете тонуть красиво, с гордостью и очень глупо.
      </p>
      <br/>
      <p class="lecture-text">
        На доске появилось три крупных строки:
      </p>
      <br/>
      <p class="lecture-text-bold">
        I. ЧТО ПЕРЕД ТОБОЙ?
      </p>
      <p class="lecture-text-bold">
        II. КАК ЭТО РАБОТАЕТ?
      </p>
      <p class="lecture-text-bold">
        III. ЧТО С ЭТИМ ДЕЛАТЬ?
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Три вопроса. Восемь шагов. Всё, что вам нужно, чтобы не наделать глупостей. Ну, по крайней мере, чтобы наделать их осознанно.
      </p>
      <br/>
      <p class="lecture-text">
        Постучал мелом по первой строке.
      </p>
      <br/>
      <p class="lecture-text-bold">
