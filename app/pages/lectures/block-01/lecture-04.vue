      </p>
      <br/>
      <p class="lecture-text-bold">
        — Бывает, что система не определяется сразу. Бывает, что символ живёт на границе двух систем или вообще вне известных вам. Это не повод бросить — это повод быть осторожнее. Незнакомая система — не пустое место. Это место, где вы гость, а правил не знаете.
      </p>
      <br/>
      <p class="lecture-text">
