      <h2 class="lecture-h2">
        Интерпретация: чтение символа и его трактовка
      </h2>

      <p class="lecture-text">
        <span class="font-extrabold">— Добро пожаловать на четвёртую вводную лекцию,</span> — Сайлас вновь громыхнул входной дверью, оповещая всех присутствующих: «вот он я: ваше спасение и ваша погибель». — <span class="font-extrabold">Сегодня мы рассмотрим то, ради чего, по-хорошему, и существует Симвология,</span> — он бросил взгляд на студентов, проверяя: живы ли. Вроде да. Хоть студентов и стало чуть меньше.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Вы можете запомнить хоть сотню символов. Можете выучить, что означает змея, круг, огонь, зеркало и почему сова — это мудрость, а не просто птица, которая смотрит на вас как на глупцов. Это полезно, — <span class="font-normal">он кивнул.</span> — Но это не делает вас символогом.
      </p>
      <br/>
      <p class="lecture-text">
        На доске размашистым почерком появилось слово: <span class="font-extrabold">ИНТЕРПРЕТАЦИЯ</span>
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Символ не существует отдельно от того, кто его читает. И вот здесь начинается самое неприятное: если вы умеете читать символы, вы неизбежно начинаете влиять на них. Иногда — даже когда не хотите. Поэтому сегодня у нас тема простая: как читать символ так, чтобы это не выглядело как «мне показалось».
      </p>
      <br/>
      <p class="lecture-text">
        <span class="font-extrabold">— И как доказывать трактовку так, чтобы я не хотел вычеркнуть ваше имя из списка живых существ этого кабинета,</span> — мужчина задорно подмигнул студентам, восхищаясь своим остроумием и совсем капельку молясь, чтобы его не закидали гнильём.
      </p>
      <br/>
      <p class="lecture-text">
        <span class="font-extrabold">— Самая частая ошибка новичков — охота за «правильным значением». Символ — это не слово в словаре: открыл, ткнул пальцем, выписал перевод и пошёл дальше жить спокойно,</span> — Сайлас лишь развёл руками. — <span class="font-extrabold">Я бы тоже так хотел, честно. Жизнь стала бы проще. Но имеем, что имеем.</span>
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Символ задаёт вопрос. И если вы ждёте от него одного ответа — вы с ним не договоритесь. Символ не выдаёт «правильно» и «неправильно». Он проверяет, насколько вы умеете думать и насколько точно вы учитываете контекст: кто создал символ, для чего, когда, где он находится сейчас. Уместность трактовки определяется этими связями, а не вашим желанием.
      </p>
      <br/>
      <p class="lecture-text">
        <span class="font-extrabold">— Вы можете смотреть на символ как на картинку. Тогда он и останется картинкой. А можете начать его читать: где он стоит, зачем он здесь, кому он адресован, что он делает. И вот тогда начинается самое приятное,</span> — он улыбнулся. — <span class="font-extrabold">Магия. И немного головной боли. Но я рядом, не переживайте. По крайней мере на время, что я буду здесь преподавать.</span>
      </p>
      <br/>
      <p class="lecture-text">
        <span class="font-extrabold">— Знаете, что я слышу чаще всего?</span> — профессор прошёлся вдоль первых парт, скрестив руки на груди. — <span class="font-extrabold">«Мне кажется…», «Я чувствую…», «Наверное, человек хотел…», «Я где-то видел…»</span>
      </p>
      <br/>
      <p class="lecture-text-bold">
        Стоп.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Я не против чувств. Совсем наоборот. Чувства — отличный инструмент. Иногда они первыми замечают то, что мозг догонит через минуту. Ты ещё не назвал объект, а уже что-то почувствовал: тревогу, узнавание, притяжение, отвращение, восторг. Не гоните их. Используйте как компас: они могут указывать направление.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Но компас — не карта. Если вы заканчиваете на «мне кажется», вы не читаете символ. Вы должны руководить чувствами, а не они вами. Иначе вы просто сообщаете своё настроение. А настроение, простите, на проверке не принимается.
      </p>
      <br/>
      <p class="lecture-text">
