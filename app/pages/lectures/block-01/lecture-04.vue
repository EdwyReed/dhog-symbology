        3. Определите систему.
      </h4>
      <p class="lecture-text">
        <span class="font-extrabold">— Вот тут начинает работать всё, что вы узнали на прошлой лекции,</span> — Сайлас кивнул в сторону стола, где всё ещё лежали вещицы с прошлого занятия. — <span class="font-extrabold">Десять систем. Десять миров. И пока вы не знаете, в каком из них символ родился, все ваши вопросы — на чужом языке.</span>
      </p>
      <br/>
      <p class="lecture-text-bold">
