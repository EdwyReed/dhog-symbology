      </p>
      <br/>
      <p class="lecture-text">
        <span class="font-extrabold">— Ах, это не то, о чём вы подумали. Просто… учебные материалы. Добро пожаловать на курс Символогии! Меня зовут Сайлас Локк, —</span> он развернулся к студентам, обводя всех счастливым взглядом.
      </p>
      <br/>
      <p class="lecture-text">
        <span class="font-extrabold">— Многие из вас слышали о рунах, гербах, алхимических знаках. Видели печати на дверях, клейма на артефактах, метки в старых книгах. Кто-то, возможно, даже трогал их без разрешения и дожил до этого утра. Поздравляю, у вас хорошие рефлексы. Так вот — всё это не разрозненные диковинки. Это части одной громадной системы. И система эта, мои прелестные обречённые слушатели, является языком магии.</span>
