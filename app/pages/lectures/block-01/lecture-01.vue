      <h2 class="lecture-h2">
        Знакомство с Символогией
      </h2>

      <p class="lecture-text">
        Кабинет Символогии наконец дожил до того состояния, в котором в него уже не стыдно было впускать студентов.
      </p>
      <br/>
      <p class="lecture-text">
