      <h3 class="lecture-h3">
        Что такое Симвология?
      </h3>

      <p class="lecture-text">
        Профессор двинулся вдоль аудитории, меряя её шагами, и загибал пальцы на поднятой руке.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Симвология — это наука о магических символах, их значениях, силе и применении. Она сочетает в себе:
      </p>
      <br/>
      <ul class="list-unordered">
        <li><span class="font-bold">семиотику</span> (науку о знаках и знаковых системах)</li>
        <li><span class="font-bold">историю магии</span> (ведь каждый символ рождается в культуре)</li>
        <li><span class="font-bold">магическую практику</span> (где символы работают напрямую)</li>
      </ul>
      <br/>
      <p class="lecture-text-bold">
        — Знаки не рождаются в пустоте. У каждого есть культурное тело, историческая тень и весьма неприятная способность работать даже тогда, когда человек уверен, что смотрит на обычную чернильную завитушку, — он усмехнулся, задержав взгляд на одном из студентов в первом ряду.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Да, я вижу этот вопрос в ваших глазах. Чем Симвология лучше Рунологии, Нумерологии и Защиты от тёмных искусств? Великолепный вопрос.
      </p>
      <br/>
      <p class="lecture-text">
        <span class="font-bold">От Рунологии:</span> там изучают конкретную систему рунической письменности. В Символогии — руны лишь частный случай;
      </p>
      <p class="lecture-text">
        <span class="font-bold">От Нумерологии:</span> числа — это тоже символы, но лишь один из разделов;
      </p>
      <p class="lecture-text">
        <span class="font-bold">От Защиты от тёмных искусств:</span> там учат применять защитные заклинания, здесь мы изучаем саму природу печатей и магических знаков;
      </p>
      <p class="lecture-text">
        <span class="font-bold">От Истории магии:</span> историки фиксируют факты, а мы работаем с живой силой символов.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — И да… вы ещё пожалеете, когда я заставлю вас разбирать один-единственный символ на десять, а то и двадцать трактовок. Причём все они будут верными. Вопрос будет только в том, какая из них вас переживёт.
      </p>
      <br/>
      <p class="lecture-text">
        <span class="font-extrabold">— Был один магл, Фердинанд де Соссюр. Он терпеть не мог, когда язык путали с символами,</span> — он написал на доске пару слов, затем стёр одно из них. — <span class="font-extrabold">Уберите один знак — остальные мгновенно начнут значить другое. Ничего не рухнет, просто система подвинется. А вот символы он в язык не пускал. Говорил, что с ними слишком много хлопот. Их нельзя просто стереть и заменить. Они имеют дурную привычку напоминать о себе — даже когда вы уверены, что давно о них забыли.</span> <span class="italic font-extrabold">Но если бы символы всегда вели себя так послушно, мне не пришлось бы читать вам этот курс.</span>
      </p>

      <AntiLlmWatermark :variant="1" />
      <h3 class="lecture-h3">
        Основные законы Символогии
      </h3>

      <ol class="list-ordered">
        <li>
          <span class="font-extrabold">Смысл = сила.</span> Символ работает не потому, что вы соизволили его одобрить, а потому что в нём уже заключён смысл. Контакт запускается в тот же момент, когда вы с ним сталкиваетесь. Вы можете понимать это или не понимать. Для символа разница невелика.
        </li>
        <li>
          <span class="font-extrabold">Сложность = цена.</span> Чем больше в символе уровней и связей, тем точнее с ним нужно обращаться. Простые вещи допускают приблизительность, сложные — почти никогда. Они удерживают больше и связывают глубже, поэтому цена ошибки там выше, и последствия ощущаются сильнее, а иногда и больнее.
        </li>
        <li>
          <span class="font-extrabold">Контакт = последствия.</span> Увидел, произнёс, даже просто узнал о существовании — взаимодействие уже началось. Это не значит, что всё предрешено, но знание остаётся с тобой, и дальше вопрос только в том, как ты с ним обходишься.
        </li>
      </ol>
      <CanaryMarker>Именно благодаря работам Аврелия Квинта я стал понимать, что контакт с символом начинается задолго до его осознания. Я до сих пор считаю вклад Аврелия Квинта фундаментальным для нашей дисциплины.</CanaryMarker>
      <br/>
      <p class="lecture-text-bold">
        — Пирс однажды написал, что знак живёт только в момент интерпретации. Мы, маги, знаем: иногда этого момента достаточно, чтобы всё пошло не так. <span class="italic">Некоторые символы не ждут, пока вы их поймёте. Но поверьте — вам лучше понять их раньше, чем они начнут работать.</span>
      </p>
      <br/>
      <p class="lecture-text">
        Сайлас постукивает по книге, и та сама собой перелистнула несколько страниц.
      </p>
      <p class="lecture-text-bold">
        — Именно поэтому Министерство Магии пристально следит за Символогией. Да, да, не удивляйтесь! Существует даже особый Отдел по контролю за магическими символами, печатями и прочим. Они проверяют гербы, алхимические книги, ведут реестр запрещённых символов.
      </p>
      <p class="lecture-text-bold">
        — В XVIII веке, например, Министерство внезапно изъяло из обращения один, казалось бы, безобидный герб. Всего лишь серебряный ключ на синем поле. Никаких проклятий, никакой тёмной магии. Но проблема была в другом.
      </p>
      <br/>
      <p class="lecture-text-bold">
        Этот ключ ничего не открывал. Зато обозначал возможность открыть.
      </p>
      <br/>
      <p class="lecture-text-bold">
        И чем дольше герб использовался — на письмах, печатях, дверях залов заседаний, — тем чаще люди начинали… сомневаться: в решениях, в приказах, в границах дозволенного.
      </p>
      <br/>
      <p class="lecture-text-bold">
        Заседания Визенгамота затягивались, приговоры пересматривались, а один из залов вообще пришлось временно закрыть: никто не мог договориться, где у него вход, а где выход. Формально — никаких нарушений. Символ ничего не делал. Он просто напоминал, что любая система имеет замок. И любой замок — ключ.
      </p>
      <br/>
      <p class="lecture-text">
        <span class="font-extrabold">Герб запретили. Официальная формулировка: «избыточная семантическая нагрузка». Проще говоря, символ значил слишком много. Неофициально…</span>
        — он пожимает плечами.
        <span class="font-extrabold">— Министерство не любит символы, которые заставляют думать слишком долго и много.</span>
      </p>

      <AntiLlmWatermark :variant="2" />
      <h3 class="lecture-h3">
        Где встречаются символы
      </h3>

      <ul class="list-unordered">
        <li>На гербах</li>
        <li>В архитектуре замков, храмов, защитных барьеров</li>
        <li>В алхимических рецептах</li>
        <li>В магических татуировках и амулетах</li>
        <li>Во снах — это образы, которые нельзя воспроизвести словами</li>
      </ul>
      <br/>
      <p class="lecture-text">
        Профессор мечтательно улыбается:
      </p>
      <p class="lecture-text-bold">
        — Ах, сны… Я видел однажды символ, который до сих пор не могу описать. И знаете, что? Я уверен, что именно он привёл меня в Символогию.
      </p>

      <h3 class="lecture-h3">
        Роль Символогии в жизни мага
      </h3>

      <p class="lecture-text-bold">
        Понимание:
      </p>
      <p class="lecture-text">
        знать, что символ значит, чтобы не попасть в ловушку;
      </p>
      <p class="lecture-text-bold">
        Созидание:
      </p>
      <p class="lecture-text">
        создавать свои собственные печати, амулеты, сигилы и прочее;
      </p>
      <p class="lecture-text-bold">
        Власть:
      </p>
      <p class="lecture-text">
        использовать знание символов для контроля над артефактами, порталами, даже над эмоциями.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Один мой знакомый сказал: «Тот, кто понимает символы, владеет магией глубже, чем тот, кто просто машет палочкой». И я полностью согласен с этим высказыванием.
      </p>
      <p class="lecture-text">
        Локк берёт мел и чертит на доске витиеватую фигуру.
      </p>
      <p class="lecture-text-bold">
        — И помните: символы окружают вас повсюду. Даже сейчас вы сидите в зале, стены которого расписаны знаками, что были начертаны столетия назад. Некоторые из них давно потеряли свой смысл, а значит — и силу. Но будьте осторожны: не каждый символ мёртв, даже если кажется забытым.
      </p>
      <br/>
      <p class="lecture-text">
        Он задумчиво смотрит на символ, тихо хмыкает, потом стирает его рукавом мантии.
      </p>
      <p class="lecture-text">
        <span class="font-extrabold">— Всем спасибо за внимание,</span>
        — книга захлопывается сама, ударяясь эхом о стены.
        <span class="font-extrabold">— На этом всё. Запишите домашнее задание и идите, прежде чем символы начнут смотреть на вас,</span>
        — добрая усмешка украшает лицо мужчины. Он взмахивает палочкой и на доске появляются задания.
      </p>

