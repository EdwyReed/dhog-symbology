      </p>

      <h4 class="lecture-h4">
        2. Руническая
      </h4>
      <p class="lecture-text">
        <span class="font-extrabold">— Руны — моя любимая тема для тех, кто считает себя смелым и романтичным,</span> — Сайлас ведёт взглядом по рядам, задерживаясь на тех, кто уже расправил плечи и явно ждёт приглашения на подвиг. — <span class="font-extrabold">С рунами не получится «я просто попробовал». С рунами выходит «я сделал», а дальше начинается самое интересное.</span>
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Руна — не буква. Руна — ключ. А ключу всё равно, насколько вы обаятельны, зато ему важно всё остальное: на чём вырезано, чем вырезано, когда вырезано и с каким намерением рука вообще полезла в эту историю. Руна на камне поведёт себя одним способом, руна на кости — другим. Вырезанная руна — не то же, что нарисованная.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Главная ошибка — собирать из рун «словечки», как из букв на плакате. Руны цепляются за материал, цель и место, и если ты обращаешься с ними как с алфавитом, они обращаются с тобой как с бумагой — мнут, рвут и не извиняются.
      </p>
      <br/>
      <p class="lecture-text italic">
        Джентльменский совет №2: если вас тянет попробовать руны ради красоты — попробуйте лучше винтажные открытки из путешествий. Тоже магия, зато без сюрпризов по ночам.
      </p>

      <h4 class="lecture-h4">
        3. Система печатей
      </h4>
      <p class="lecture-text-bold">
        — Мир прав и полномочий. Печать — это не картинка. Это момент, когда воск принимает форму, — вот где магия. Оттиск говорит: «я, имеющий право, удостоверяю».
      </p>
      <br/>
      <p class="lecture-text">
        Теперь его пальцы подхватили кусок воска. Он поднял его левитацией, разворачивая так, чтобы всем была видна трещина, проходящая точно по центру оттиска.
      </p>
      <br/>
      <p class="lecture-text">
        <span class="font-extrabold">— Глазки сюда. Кто-то поставил печать… а потом кто-то её переломал. Видите трещину? В системе печатей это не «ой, неловко вышло». Это зафиксированное действие. Либо письмо вскрывали, либо право отменили. Сломанная печать — не испорченный воск, это поломанное право. А если право было жирное…</span> — он опустил воск обратно на свой стол. — <span class="font-extrabold">…то и последствия будут жирные.</span>
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Чужую печать нельзя одолжить, нельзя скопировать, нельзя «просто попробовать». Печать — это право, а право либо есть, либо нет.
      </p>
