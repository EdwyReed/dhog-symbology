      <br/>
      <p class="lecture-text-bold">
        — Это единственная система, где символ работает не через понимание и не через технику. Здесь не важно, умеешь ты или не умеешь. Важно одно: власть признаёт тебя — или смеётся тебе в лицо.
      </p>

      <h4 class="lecture-h4">
        4. Система сигилов
      </h4>
      <p class="lecture-text-bold">
        — Сигилы — это авторские подписи у магии. Ты придумал, ты вложил намерение, ты оживил — и оно пошло по миру. Они скорее как маленькое существо: у него есть цель, и оно её помнит.
      </p>
      <br/>
      <p class="lecture-text">
        Сайлас поднял медный кругляш и пустил по студентам.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Посмотрите сюда: на меди не рисуночек, а чужая подпись. Сигил не обязан быть понятным — он обязан срабатывать, и вы узнаете, сработал ли он уже или ещё нет, только в тот момент, когда окажетесь достаточно близко, чтобы это стало уже вашей проблемой.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — В гримуарной традиции сигилы — это имена и печати сущностей: чертишь знак — и то, что за ним стоит, слышит тебя. В хаос-магии дорожка другая: ты сам собираешь знак из собственного намерения, заряжаешь, выбрасываешь из головы — и он пашет без няньки в виде сознания. Общее одно: сигил — это всегда сделка.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Главная подстава: про сигил можно забыть, а он про тебя — нет. Он просто перестаёт быть под контролем. Работает дальше, но уже сам по себе. Иногда это ничего. Иногда — очень даже что-то.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — И ещё одна взрослая вещь: многие сигилы работают «в кредит». Плата бывает смешной… пока не перестаёт быть смешной.
      </p>
