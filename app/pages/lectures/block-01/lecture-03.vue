      <h4 class="lecture-h4">
        1. Геральдическая
      </h4>
      <p class="lecture-text-bold">
        Мир имён, рода и принадлежности. Гербы, щиты, девизы — знакомство ещё не началось, а тебя уже представили, оценили и мысленно внесли в список родственников, врагов и людей, которым нельзя доверять столовое серебро. Геральдика говорит вместо владельца, и у этого языка есть строгая грамматика. Цвета, деления, фигуры и их расстановка держатся за порядок крепче, чем завхоз за ключи, а любое сочетание выдаёт историю.
      </p>
      <br/>
      <p class="lecture-text">
        Сайлас взял со стола перстень, покрутил его на свету и, не теряя времени, поднял заклинанием Wingardium Leviosa. Кольцо плавало вдоль рядов, останавливаясь у каждого студента на пару секунд. На ободке хорошо видно гравировку: грифон и полумесяц.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Смотрите внимательно. Камень вылетел, а гравировка на месте. Камень — деталь, его меняют. А гравировка держится, потому что это имя и принадлежность. Это то, что кольцо сообщает за владельца.
      </p>
      <br/>
      <p class="lecture-text-bold">
        — Главная задача геральдики — узнавание. Главная проблема — взять чужое. Иногда кто-то пришивает себе симпатичный щиток ради эффектности, а потом внезапно выясняется, что он подписался под чужой историей, чужими врагами и чужими обязательствами. И да, это всплывает в самый неподходящий момент.
